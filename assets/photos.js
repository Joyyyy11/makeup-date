/* 构建远程 URL 并优先返回本地已下载文件 */
function photo(id, w = 600, h = 900) {
  const remote = `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${w}&h=${h}&q=72`;
  const map = (typeof window !== 'undefined' && window.__IMG_MAP) || null;
  if (map && map[remote]) return map[remote];
  return remote;
}

/* 内联 SVG 占位图，避免任何外链依赖。用法 ph(w, h, label) */
function ph(w, h, label) {
  if (typeof w === 'string') { label = w; w = 600; h = 900; }
  w = w || 600; h = h || 900;
  const t = String(label || 'MAKEUP DATE');
  const size = Math.round(Math.min(w, h) / 12);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#F7F6F4"/><stop offset="1" stop-color="#EDEAE4"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/><text x="50%" y="50%" font-family="Inter,sans-serif" font-size="${size}" fill="#C5A059" text-anchor="middle" dominant-baseline="middle">${t.replace(/[<>&]/g, '')}</text></svg>`;
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

/* 返回 <img> 标签 */
function img(id, o) {
  o = o || {};
  const w = o.w || 560, h = o.h || 800;
  const alt = (o.alt || '').replace(/"/g, '&quot;');
  return `<img src="${photo(id, w, h)}" alt="${alt}" width="${w}" height="${h}" loading="${o.eager ? 'eager' : 'lazy'}">`;
}

/* 化妆师头像：不使用作品图，改为文字徽章
   —— 女性用暖金渐变，男性用曜石黑，中间显示性别首字 */
function avatar(a) {
  // 兼容旧调用：传入字符串 id 时退化为中性徽章
  if (typeof a === 'string') {
    return `<span class="look-avatar av-neutral" aria-hidden="true">M</span>`;
  }
  const g = a.gender || '女';
  const isM = g === '男';
  const ch = isM ? '男' : '女';
  const cls = isM ? 'av-male' : 'av-female';
  const title = `${a.name} · ${g} · ${a.years} 年经验`;
  return `<span class="look-avatar ${cls}" title="${title}" aria-label="${title}">${ch}</span>`;
}

/* 化妆师资历徽章：性别 · 从业年限 · 擅长妆造 */
function credBadge(a) {
  const g = a.gender || '女';
  const skills = (a.styles || []).slice(0, 2).join(' / ');
  return `<span class="cred-badge">${g} · ${a.years}年 · ${skills}</span>`;
}

